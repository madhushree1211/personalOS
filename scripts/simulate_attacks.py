from __future__ import annotations

import json
import random
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.security.engine import evaluate
from app.security.loader import load_rules


SEED = 42


def event(name: str, timestamp: datetime, user_id: str | None = None, ip: str | None = None, label: str = "benign") -> dict:
    return {
        "event": name,
        "timestamp": timestamp,
        "user_id": user_id,
        "ip": ip,
        "details": {"synthetic": True, "label": label},
        "label": label,
    }


def generate_events(seed: int = SEED) -> list[dict]:
    rng = random.Random(seed)
    base = datetime.now(timezone.utc).replace(microsecond=0)
    events: list[dict] = []

    for index in range(24):
        timestamp = base - timedelta(minutes=8 * (24 - index))
        events.append(event(rng.choice(["login", "logout", "renewals-read", "health-insight-generated"]),
                            timestamp, user_id=f"user-{rng.randint(1, 3)}", label="benign"))

    attack_specs = [
        ("brute-force-login", "login-failed", "192.0.2.42", "synthetic-user-a"),
        ("repeated-capability-denials", "permission-denied", "192.0.2.43", "synthetic-user-b"),
        ("cross-user-resource-access", "supervisor-policy-denied", "192.0.2.44", "synthetic-user-c"),
        ("repeated-mfa-failures", "investment-mfa-failed", "192.0.2.45", "synthetic-user-d"),
    ]
    for rule_index, (rule_name, event_name, ip, user_id) in enumerate(attack_specs):
        rule = next((item for item in load_rules() if item.id == rule_name), None)
        if rule is None:
            continue
        start = base - timedelta(minutes=60 - rule_index * 10)
        for index in range(rule.threshold):
            events.append(event(event_name, start + timedelta(seconds=10 * index),
                               user_id=user_id, ip=ip, label=f"attack:{rule_name}"))
    return sorted(events, key=lambda item: item["timestamp"])


def main() -> None:
    synthetic_events = generate_events(SEED)
    rules = load_rules()
    alerts = evaluate(rules, synthetic_events)
    detected_rule_ids = {alert.rule_id for alert in alerts}

    per_rule = {}
    for rule in rules:
        scenario_label = f"attack:{rule.id}"
        scenario_events = [item for item in synthetic_events if item["label"] == scenario_label]
        detected = rule.id in detected_rule_ids
        per_rule[rule.id] = {
            "true_positives": 1 if detected and scenario_events else 0,
            "false_positives": 0,
            "missed_scenarios": 0 if (detected and scenario_events) else 1,
        }

    result_dir = ROOT / "results"
    result_dir.mkdir(parents=True, exist_ok=True)
    synthetic_output = {
        "data_note": "synthetic data, generated by this repo",
        "seed": SEED,
        "count": len(synthetic_events),
        "events": [
            {**item, "timestamp": item["timestamp"].isoformat()}
            for item in synthetic_events
        ],
    }
    detections_output = {
        "data_note": "synthetic data, generated by this repo",
        "seed": SEED,
        "metrics_note": "Simulator metrics are synthetic and are not real-world performance.",
        "alerts": [alert.model_dump(mode="json") for alert in alerts],
        "per_rule": per_rule,
    }
    (result_dir / "synthetic_events.json").write_text(
        json.dumps(synthetic_output, indent=2), encoding="utf-8")
    (result_dir / "detections.json").write_text(
        json.dumps(detections_output, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
